#!/usr/bin/env python3
"""Compile a version 1 keyboard definition into a read-only C++ layout table."""

import argparse
import json
import math
import os
from pathlib import Path
import re
import struct
import tempfile


ACTION_TYPES = {
    "insert": "Insert",
    "switch_layout": "SwitchLayout",
    "shift": "Shift",
    "shift_lock": "ShiftLock",
    "backspace": "Backspace",
    "enter": "Enter",
}


def object_at(value, field):
    if not isinstance(value, dict):
        raise ValueError(f"{field} must be an object")
    return value


def array_at(value, field):
    if not isinstance(value, list) or not value:
        raise ValueError(f"{field} must be a non-empty array")
    return value


def string_at(value, field):
    if not isinstance(value, str) or not value or "\0" in value:
        raise ValueError(f"{field} must be a non-empty string without NUL characters")
    return value


def id_at(value, field, allow_uppercase=False):
    name = string_at(value, field)
    suffix = "[a-zA-Z0-9_-]*" if allow_uppercase else "[a-z0-9_-]*"
    if not re.fullmatch("[a-z]" + suffix, name):
        raise ValueError(f"{field} must be a keyboard identifier")
    return name


def geometry_at(value, field, allow_zero=False):
    if type(value) not in (int, float):
        raise ValueError(f"{field} must be a number")
    try:
        width = struct.unpack("f", struct.pack("f", value))[0]
    except (OverflowError, struct.error) as error:
        raise ValueError(f"{field} must fit in a C++ float") from error
    if not math.isfinite(width) or value < 0 or (not allow_zero and width == 0):
        minimum = "non-negative" if allow_zero else "positive"
        raise ValueError(f"{field} must be finite and {minimum}")
    return width


def cpp_string(value):
    # Octal escapes preserve UTF-8 regardless of the C++ execution charset.
    parts = ['"']
    for byte in value.encode("utf-8"):
        if byte in (ord('"'), ord("\\")):
            parts.append("\\" + chr(byte))
        elif 32 <= byte <= 126:
            parts.append(chr(byte))
        else:
            parts.append(f"\\{byte:03o}")
    parts.append('"')
    return "".join(parts)


def cpp_float(value):
    return f"{value!r}f"


def layout_target(value, field, options):
    name = string_at(value, field)
    if name not in options:
        raise ValueError(f"{field} references an unavailable layout {name!r}")
    return name


def action_source(value, field, base_layouts, layout_index):
    action = object_at(value, field)
    kind = string_at(action.get("type"), f"{field}.type")
    if kind not in ACTION_TYPES:
        raise ValueError(f"{field}.type has unsupported action {kind!r}")

    fields = {"type"}
    text = "nullptr"
    target = "no_layout"
    if kind == "insert":
        fields.add("text")
        text = cpp_string(string_at(action.get("text"), f"{field}.text"))
    elif kind == "switch_layout":
        fields.add("layout")
        name = layout_target(action.get("layout"), f"{field}.layout", base_layouts)
        target = layout_index[name]
    if action.keys() != fields:
        raise ValueError(f"{field} has unexpected fields for {kind!r}")
    return f"{{ActionType::{ACTION_TYPES[kind]}, {text}, {target}}}"


def generate(profile):
    profile = object_at(profile, "profile")
    if type(profile.get("version")) is not int or profile["version"] != 1:
        raise ValueError("profile.version must be 1")
    id_at(profile.get("id"), "profile.id", allow_uppercase=True)
    width = geometry_at(profile.get("width"), "profile.width")
    layouts = object_at(profile.get("layouts"), "profile.layouts")
    layout_index = {name: index for index, name in enumerate(layouts)}
    shift_targets = {}
    for name, layout in layouts.items():
        id_at(name, "layout name")
        field = f"layouts.{name}"
        layout = object_at(layout, field)
        if "shiftedLayout" in layout:
            shift_targets[name] = layout_target(layout["shiftedLayout"], f"{field}.shiftedLayout", layouts)

    for source, target in shift_targets.items():
        if target in shift_targets:
            raise ValueError(f"layouts.{source}.shiftedLayout must point to a layout without a shifted layout")
    base_layouts = layouts.keys() - shift_targets.values()
    initial = layout_target(profile.get("initialLayout"), "profile.initialLayout", base_layouts)

    lines = [
        "// Generated by Keyboard/generate_layout.py.",
        "#pragma once",
        "",
        '#include "LayoutData.h"',
        "",
        "namespace espos::keyboard::detail {",
        "",
    ]
    layout_lines = []
    max_keys = 0
    for name, layout in layouts.items():
        layout_field = f"layouts.{name}"
        rows = array_at(layout.get("rows"), f"{layout_field}.rows")
        prefix = f"en_us_qwerty_{layout_index[name]}"
        row_lines = []
        key_ids = set()
        for row_index, row in enumerate(rows):
            row_field = f"{layout_field}.rows[{row_index}]"
            row = object_at(row, row_field)
            offset = geometry_at(row.get("offset", 0), f"{row_field}.offset", allow_zero=True)
            keys = array_at(row.get("keys"), f"{row_field}.keys")
            table = f"{prefix}_row_{row_index}"
            widths = [offset]
            lines.append(f"inline constexpr Key {table}[] = {{")
            for column, key in enumerate(keys):
                key_field = f"{row_field}.keys[{column}]"
                key = object_at(key, key_field)
                key_id = id_at(key.get("id"), f"{key_field}.id")
                if key_id in key_ids:
                    raise ValueError(f"{key_field}.id duplicates {key_id!r} in the layout")
                key_ids.add(key_id)
                label = cpp_string(string_at(key.get("label"), f"{key_field}.label"))
                key_width = geometry_at(key.get("width", 1), f"{key_field}.width")
                widths.append(key_width)
                tap = action_source(key.get("action"), f"{key_field}.action", base_layouts, layout_index)
                double_tap = "{ActionType::None, nullptr, no_layout}"
                if "doubleTapAction" in key:
                    double_tap = action_source(key["doubleTapAction"], f"{key_field}.doubleTapAction",
                                               base_layouts, layout_index)
                lines.append(f"    {{{cpp_string(key_id)}, {label}, {cpp_float(key_width)}, {tap}, {double_tap}}},")
            if math.fsum(widths) > width * (1 + 1e-6):
                raise ValueError(f"{row_field} is wider than profile.width")
            lines += ["};", ""]
            row_lines.append(f"    {{{cpp_float(offset)}, {table}, {len(keys)}}},")
        lines += [f"inline constexpr Row {prefix}_rows[] = {{", *row_lines, "};", ""]
        shifted = layout_index[shift_targets[name]] if name in shift_targets else "no_layout"
        layout_lines.append(f"    {{{prefix}_rows, {len(rows)}, {shifted}}},")
        max_keys = max(max_keys, len(key_ids))

    lines += [
        "inline constexpr Layout en_us_qwerty_layouts[] = {",
        *layout_lines,
        "};",
        "",
        "inline constexpr LayoutDefinition en_us_qwerty{",
        f"    {cpp_float(width)}, en_us_qwerty_layouts, {len(layouts)}, {layout_index[initial]}, {max_keys},",
        "};",
        "",
        "}  // namespace espos::keyboard::detail",
        "",
    ]
    return "\n".join(lines).encode("ascii")


def write_header(path, data):
    if path.is_file() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as output:
            temporary = Path(output.name)
            output.write(data)
        os.replace(temporary, path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def unique_properties(pairs):
    result = {}
    for name, value in pairs:
        if name in result:
            raise ValueError(f"duplicate JSON property {name!r}")
        result[name] = value
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("definition", type=Path)
    parser.add_argument("header", type=Path)
    args = parser.parse_args()
    try:
        if args.definition.resolve() == args.header.resolve():
            raise ValueError("the definition and generated header must be different files")
        profile = json.loads(args.definition.read_text(encoding="utf-8"), object_pairs_hook=unique_properties)
        data = generate(profile)
        write_header(args.header, data)
    except (OSError, ValueError) as error:
        parser.error(f"{args.definition}: {error}")


if __name__ == "__main__":
    main()
