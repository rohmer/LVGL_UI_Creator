#!/usr/bin/env python3
"""Extract the MIT-licensed, vendored LVGL Pinyin character dictionary."""
import argparse
from pathlib import Path
import re
from generate_layout import cpp_string, write_header

HERE = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=HERE.parents[3] / '3rdParty/LVGL/lvgl/src/widgets/ime/lv_ime_pinyin.c')
    parser.add_argument('--output', type=Path, default=HERE.parent / 'PinyinData.inc')
    args = parser.parse_args()
    source = args.source.read_text(encoding='utf-8')
    block = re.search(r'static const lv_pinyin_dict_t lv_ime_pinyin_def_dict\[\]\s*=\s*\{(.*?)\n\};', source, re.S)
    if not block:
        raise ValueError('Vendored LVGL Pinyin dictionary was not found')
    entries = re.findall(r'\{\s*"([a-z]+)"\s*,\s*"([^"\n]+)"\s*\}', block.group(1))
    if not entries or len({key for key, _ in entries}) != len(entries):
        raise ValueError('Empty or duplicate Pinyin dictionary keys')
    if any(len(key) > 7 or any(len(char.encode('utf-8')) > 4 for char in text) for key, text in entries):
        raise ValueError('Dictionary exceeds the fixed composition limits')
    lines = ['// Generated by layout/generate_pinyin.py from vendored LVGL 9.6.',
             '// MIT license: see PinyinData.LICENSE.txt. Character order is preserved.']
    lines += ['{' + cpp_string(key) + ', ' + cpp_string(text) + '},' for key, text in sorted(entries)]
    write_header(args.output, ('\n'.join(lines) + '\n').encode('utf-8'))
    print(f'Extracted {len(entries)} Pinyin spellings')


if __name__ == '__main__':
    main()
