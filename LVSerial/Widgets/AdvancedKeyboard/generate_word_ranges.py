"""Generate the keyboard's immutable Unicode categories from the model tables.

The output is checked in; normal device/desktop builds do not require Python.
"""
from pathlib import Path
import re

directory = Path(__file__).resolve().parent
source = (directory.parents[2] / "UICreator/LanguageModels/UnicodeTables.inc").read_text()
output = ["// Generated by generate_word_ranges.py from the generator's Unicode 14.0 tables.\n"]
for original, name in [("kWordRanges", "kUnicodeWordRanges"), ("kMarkRanges", "kUnicodeMarkRanges")]:
    body = re.search(r"constexpr Range " + original + r"\[\] = \{(.*?)\n\};", source, re.S)[1]
    output.append("constexpr WordRange " + name + "[] = {" + body + "\n};\n")
body = re.search(r"constexpr Pair kLower\[\] = \{(.*?)\n\};", source, re.S)[1]
lower = [(int(first, 16), int(second, 16)) for first, second in re.findall(r"\{(0x[0-9a-f]+), (0x[0-9a-f]+)\}", body)]
lower = [(first, second) for first, second in lower if 0x400 <= first <= 0x52f or 0xa640 <= first <= 0xa69f]
upper = sorted((second, first) for first, second in lower)
assert len({first for first, _ in upper}) == len(upper)
assert all(len(chr(first).encode("utf-8")) == len(chr(second).encode("utf-8")) for first, second in lower)
for name, values in [("kCyrillicLowerMappings", lower), ("kCyrillicUpperMappings", upper)]:
    output.append("constexpr ScalarMapping " + name + "[] = {\n")
    output.extend(f"    {{0x{first:x}, 0x{second:x}}},\n" for first, second in values)
    output.append("};\n")
body = re.search(r"constexpr Decomposition kDecompositions\[\] = \{(.*?)\n\};", source, re.S)[1]
decompositions = {int(scalar, 16): (int(first, 16), int(second, 16)) for scalar, first, second in
                  re.findall(r"\{(0x[0-9a-f]+), (0x[0-9a-f]+), (0x[0-9a-f]+)\}", body)}
output.append("// These eleven canonical decompositions are NFC composition exclusions.\nconstexpr IndicDecomposition kIndicNuktaMappings[] = {\n")
for scalar in [*range(0x958, 0x960), 0x9dc, 0x9dd, 0x9df]:
    first, second = decompositions[scalar]
    output.append(f"    {{0x{scalar:x}, 0x{first:x}, 0x{second:x}}},\n")
output.append("};\n")
target = directory / "UnicodeWordRanges.inc"
target.write_text("\n".join(output), encoding="utf-8", newline="\n")
print(target, target.stat().st_size, "source bytes;", len(lower), "Cyrillic case pairs")
