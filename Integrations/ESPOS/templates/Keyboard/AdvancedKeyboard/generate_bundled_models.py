"""Generate selected, checked NGTR/NGIX flash assets without runtime JSON/files."""
from __future__ import annotations
import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import tempfile


def selected_models(catalog: dict, choice: str) -> list[dict]:
    if catalog.get("version") != 1 or not isinstance(catalog.get("models"), list):
        raise ValueError("Unsupported bundled model catalog")
    by_pair = {}
    for record in catalog["models"]:
        if not isinstance(record, dict):
            raise ValueError("Invalid bundled model metadata")
        language, size = record.get("language"), record.get("sizeKiB")
        filename, checksum = record.get("filename"), record.get("sha256")
        if not isinstance(language, str) or not re.fullmatch(r"[a-z]{2,3}-[A-Z]{2}", language):
            raise ValueError("Invalid bundled model language")
        if type(size) is not int or size not in (16, 256):
            raise ValueError("Invalid bundled model size")
        if not isinstance(filename, str) or Path(filename).name != filename or "/" in filename or "\\" in filename or not filename.endswith(".ngtr"):
            raise ValueError("Bundled model filenames must stay in the models directory")
        if not isinstance(checksum, str) or not re.fullmatch(r"[0-9a-f]{64}", checksum):
            raise ValueError("Invalid bundled model checksum")
        if type(record.get("bytes")) is not int or not 20 <= record["bytes"] <= 16 * 1024 * 1024:
            raise ValueError("Invalid bundled model byte length")
        if not isinstance(record.get("name"), str) or not record["name"] or any(ch in record["name"] for ch in "\0\r\n"):
            raise ValueError("Invalid bundled model name")
        pair = (language, size)
        if pair in by_pair:
            raise ValueError("Duplicate bundled model language/size")
        by_pair[pair] = record
    choice = choice.strip()
    if choice in ("", "none"):
        return []
    if choice == "all":
        return list(by_pair.values())
    result, seen = [], set()
    for item in re.split(r"[;,]", choice):
        pieces = item.strip().split(":")
        if len(pieces) != 2 or not pieces[1].isdigit():
            raise ValueError("Choose models as language:KiB pairs, for example en-US:16;zh-CN:256")
        pair = (pieces[0], int(pieces[1]))
        if pair in seen:
            raise ValueError("Duplicate selected bundled model")
        seen.add(pair)
        if pair not in by_pair:
            raise ValueError("Unknown bundled model selection: " + item)
        result.append(by_pair[pair])
    return result


def atomic_write(path: Path, data: bytes) -> None:
    if path.is_file() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(data)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def generate(catalog_path: Path, index_builder: Path, choice: str, output: Path, report: Path | None = None) -> dict:
    catalog_path, index_builder = catalog_path.resolve(), index_builder.resolve()
    catalog = json.loads(catalog_path.read_text(encoding="utf-8"))
    records = selected_models(catalog, choice)
    spec = importlib.util.spec_from_file_location("advanced_keyboard_ngix", index_builder)
    if not spec or not spec.loader:
        raise ValueError("Cannot load the bundled NGIX builder")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    models_root = (catalog_path.parent / "models").resolve()
    prepared = []
    for record in records:
        path = (models_root / record["filename"]).resolve()
        if not path.is_relative_to(models_root):
            raise ValueError("Bundled model path escapes the models directory")
        data = path.read_bytes()
        if len(data) != record["bytes"] or hashlib.sha256(data).hexdigest() != record["sha256"]:
            raise ValueError("Bundled model does not match catalog: " + record["filename"])
        index = bytes(module.build_index(data))
        if len(index) != record.get("indexBytes"):
            raise ValueError("Bundled model index does not match catalog: " + record["filename"])
        prepared.append((record, data, index))
    lines = [
        "// Generated by generate_bundled_models.py; selected immutable flash assets.",
        '#include "espos_keyboard/BundledModels.h"',
        "namespace espos::keyboard::bundled::detail {",
        "namespace {",
    ]
    def array(name: str, data: bytes) -> None:
        lines.append("alignas(4) const unsigned char " + name + "[] = {")
        for position in range(0, len(data), 24):
            lines.append("    " + ",".join(f"0x{byte:02x}" for byte in data[position:position + 24]) + ",")
        lines.append("};")
    for number, (_, data, index) in enumerate(prepared):
        array(f"trie_{number}", data)
        array(f"index_{number}", index)
    if prepared:
        lines.append("const Model models[] = {")
        for number, (record, data, index) in enumerate(prepared):
            lines.append("    {" + ", ".join([
                json.dumps(record["language"]), json.dumps(record["name"], ensure_ascii=True), str(record["sizeKiB"]),
                str(len(data)), str(len(index)), f"trie_{number}", f"index_{number}",
            ]) + "},")
        lines.append("};")
    lines.append("}")
    lines.append("const Model* GeneratedModels() noexcept { return " + ("models" if prepared else "nullptr") + "; }")
    lines.append("std::size_t GeneratedCount() noexcept { return " + str(len(prepared)) + "; }")
    lines.append("}")
    result = {"models": [{key: record[key] for key in ("language", "sizeKiB", "bytes", "indexBytes", "sha256")} for record, _, _ in prepared],
              "count": len(prepared), "trieBytes": sum(len(data) for _, data, _ in prepared),
              "indexBytes": sum(len(index) for _, _, index in prepared)}
    # All selected models have been validated before either output is replaced.
    atomic_write(output, ("\n".join(lines) + "\n").encode())
    if report:
        atomic_write(report, (json.dumps(result, indent=2) + "\n").encode())
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, required=True)
    parser.add_argument("--index-builder", type=Path, required=True)
    parser.add_argument("--models", default="en-US:16")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    print(json.dumps(generate(args.catalog, args.index_builder, args.models, args.output, args.report)))


if __name__ == "__main__":
    main()
