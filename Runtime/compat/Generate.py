"""Regenerate runtime flag adapters from generator helpers and pinned capability tables.
Run from any directory with Python 3. This is a development tool, not a firmware dependency.
"""
from pathlib import Path
import json
import re
root = Path(__file__).resolve().parents[2]
caps_text = (root / 'CodeGeneration/Targets/Capabilities.h').read_text()
caps = json.loads(re.search(r'R"\w*\((.*)\)\w*"', caps_text, re.S)[1])
for major in (9, 8):
    source = (root / f'CodeGeneration/Targets/Compat{major}.h').read_text()
    def adapt(match):
        name = match[2]
        block = match[0]
        if name == 'state':
            return block
        is_state = name in ('checked', 'disabled') or name.startswith('state_user_')
        versions = [v for v, c in caps.items() if v.startswith(str(major)+'.') and name.upper() in c['flags']]
        if match[1] == 'void' and f'lv_obj_is_{name}(' not in source:
            flag = re.search(r'LV_OBJ_FLAG_\w+', block)
            state = re.search(r'LV_STATE_\w+', block)
            token = flag or state
            if token:
                block += f'\nstatic inline bool lv_obj_is_{name}(const lv_obj_t* object) {{ return lv_obj_has_'+('flag' if flag else 'state')+f'(object, {token[0]}); }}\n'
        if is_state:
            return block
        condition = ' || '.join(f'(LVGL_VERSION_MAJOR == {v.split(".")[0]} && LVGL_VERSION_MINOR == {v.split(".")[1]})' for v in versions) or '0'
        return f'#if {condition}\n{block}\n#endif\n'
    result = re.sub(r'static inline (void|bool) lv_obj_(?:set|is)_(\w+)\([^)]*\)\s*\{[^{}]*\}', adapt, source)
    result = result.replace('ui_compat_states', 'lvgl_runtime_compat_states')
    (Path(__file__).parent / f'Compat{major}.h').write_text('// Generated by Generate.py; edit the source helpers or capability table.\n'+result)
