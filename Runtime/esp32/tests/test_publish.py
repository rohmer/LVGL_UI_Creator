import errno
from pathlib import Path
import sys
import tempfile
import unittest
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from make_component import rename_generated_directory


def windows_lock(code=5):
    error = PermissionError(errno.EACCES, "Generated directory is temporarily busy")
    error.winerror = code
    return error


class GeneratedDirectoryPublishTests(unittest.TestCase):
    def temporary(self):
        root = Path(__file__).resolve().parents[3] / "build/esp32-publish-tests"
        root.mkdir(parents=True, exist_ok=True)
        return tempfile.TemporaryDirectory(dir=root)

    def fixture(self, root):
        source, destination = root / "stage", root / "published"
        source.mkdir()
        (source / "payload.txt").write_text("complete generated bytes")
        return source, destination

    def test_transient_windows_locks_retry_then_publish_intact(self):
        for code in (5, 32, 33):
            with self.subTest(winerror=code), self.temporary() as temporary:
                source, destination = self.fixture(Path(temporary))
                actual_rename = Path.rename
                attempts = []

                def locked(path, target):
                    attempts.append((path, target))
                    if len(attempts) < 3:
                        raise windows_lock(code)
                    return actual_rename(path, target)

                with mock.patch.object(Path, "rename", locked), mock.patch("make_component.time.sleep") as sleep:
                    rename_generated_directory(source, destination)
                self.assertEqual(len(attempts), 3)
                self.assertEqual(sleep.call_args_list, [mock.call(0.05), mock.call(0.1)])
                self.assertFalse(source.exists())
                self.assertEqual((destination / "payload.txt").read_text(), "complete generated bytes")

    def test_persistent_windows_lock_is_bounded_and_preserves_source(self):
        with self.temporary() as temporary:
            source, destination = self.fixture(Path(temporary))
            error = windows_lock()
            with mock.patch.object(Path, "rename", side_effect=error) as rename, \
                    mock.patch("make_component.time.sleep") as sleep:
                with self.assertRaises(PermissionError) as raised:
                    rename_generated_directory(source, destination)
            self.assertIs(raised.exception, error)
            self.assertEqual(rename.call_count, 7)
            self.assertEqual(sleep.call_count, 6)
            self.assertLessEqual(sum(round(call.args[0] * 1000) for call in sleep.call_args_list), 2550)
            self.assertEqual((source / "payload.txt").read_text(), "complete generated bytes")
            self.assertFalse(destination.exists())

    def test_existing_destination_is_never_replaced(self):
        with self.temporary() as temporary:
            source, destination = self.fixture(Path(temporary))
            destination.mkdir()
            with mock.patch.object(Path, "rename") as rename, mock.patch("make_component.time.sleep") as sleep:
                with self.assertRaises(FileExistsError):
                    rename_generated_directory(source, destination)
            rename.assert_not_called()
            sleep.assert_not_called()
            self.assertTrue(destination.is_dir())
            self.assertEqual((source / "payload.txt").read_text(), "complete generated bytes")

    def test_destination_created_during_retry_is_preserved(self):
        with self.temporary() as temporary:
            source, destination = self.fixture(Path(temporary))

            def concurrent_destination(_delay):
                destination.mkdir()
                (destination / "user.txt").write_text("concurrent user work")

            with mock.patch.object(Path, "rename", side_effect=windows_lock()) as rename, \
                    mock.patch("make_component.time.sleep", side_effect=concurrent_destination):
                with self.assertRaises(FileExistsError):
                    rename_generated_directory(source, destination)
            self.assertEqual(rename.call_count, 1)
            self.assertEqual((destination / "user.txt").read_text(), "concurrent user work")
            self.assertEqual((source / "payload.txt").read_text(), "complete generated bytes")

    def test_other_filesystem_errors_are_not_retried(self):
        with self.temporary() as temporary:
            source, destination = self.fixture(Path(temporary))
            error = PermissionError(errno.EACCES, "Persistent POSIX permission error")
            with mock.patch.object(Path, "rename", side_effect=error) as rename, \
                    mock.patch("make_component.time.sleep") as sleep:
                with self.assertRaises(PermissionError) as raised:
                    rename_generated_directory(source, destination)
            self.assertIs(raised.exception, error)
            rename.assert_called_once()
            sleep.assert_not_called()
            self.assertTrue(source.is_dir())


if __name__ == "__main__":
    unittest.main()
