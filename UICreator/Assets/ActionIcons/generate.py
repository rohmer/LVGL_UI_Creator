"""Generate action SVGs and the shared native LVGL action catalog (stdlib only)."""
from __future__ import annotations
import argparse
import html
import importlib.util
import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parent
sys.dont_write_bytecode=True
spec=importlib.util.spec_from_file_location('uicreator_object_icon_geometry',ROOT.parent/'ObjectIcons/generate.py')
geometry=importlib.util.module_from_spec(spec)
spec.loader.exec_module(geometry)

REQUIRED=set('''new open save save-as exit undo redo duplicate delete copy paste move-up move-down
events-editor layout-designer property-search align-left align-hcenter align-right align-top align-vcenter
align-bottom distribute-horizontal distribute-vertical commands device-previews screen-flow problems
fit-canvas zoom-reset zoom-in zoom-out view:all preferences view:screens view:widgets view:hierarchy
view:properties view:tools view:simulator theme-gallery component-library font-manager image-manager
font-converter image-converter model-playground language-model-generator language-model-load
export-protobuf export-c project-creator device-tools run-toggle run-application run-stop performance
validate-screen debug-screen debug-stop welcome shortcuts diagnostics about screen-add screen-home
select-screen grid-decrease grid-increase variable-add variable-delete minimize restore close settings add remove'''.split())
REQUIRED.update('menu:'+name for name in ('File','Edit','View','Assets','Language Models','Export','Debug','Help'))
REQUIRED.update('submenu:'+name for name in ('Recent projects','Align','Distribute','Show panel'))

def outputs():
    source={entry['key']:entry for family in ('widgets','bootstrap','templates')
        for entry in json.loads((ROOT.parent/'ObjectIcons'/(family+'.json')).read_text(encoding='utf-8'))}
    entries=json.loads((ROOT/'actions.json').read_text(encoding='utf-8'))
    if [entry['id'] for entry in entries]!=list(range(len(entries))):
        raise ValueError('Action IDs must be contiguous and ordered')
    keys=set();aliases=set();prefixes=set();records=[];generated={};manifest=[]
    native=['// Generated by Assets/ActionIcons/generate.py. Edit actions.json, then regenerate.']
    for index,entry in enumerate(entries):
        key=entry['key'];name=entry['name']
        if not key.startswith('action.') or key in keys or any(c not in 'abcdefghijklmnopqrstuvwxyz0123456789._-' for c in key):
            raise ValueError('Invalid or repeated action key: '+key)
        keys.add(key)
        if not isinstance(name,str) or not name or not entry.get('aliases'):
            raise ValueError('Missing action label or explicit aliases: '+key)
        for alias in entry['aliases']:
            if not isinstance(alias,str) or not alias or alias in aliases:
                raise ValueError('Invalid or repeated action binding: '+str(alias))
            aliases.add(alias)
        for prefix in entry.get('prefixes',[]):
            if prefix!='recent:' or prefix in prefixes:
                raise ValueError('Unsupported or repeated dynamic action prefix: '+str(prefix))
            prefixes.add(prefix)
        if ('commands' in entry)==('reuse' in entry):
            raise ValueError('Specify geometry or one explicit object-icon reuse: '+key)
        commands=entry.get('commands')
        if commands is None:
            if entry['reuse'] not in source:raise ValueError('Unknown source object icon: '+entry['reuse'])
            commands=source[entry['reuse']]['commands']
        if not commands:raise ValueError('Empty action geometry: '+key)
        primitive=[item for command in commands for item in geometry.primitives(command)]
        if len(primitive)>65535:raise ValueError('Action has too many native primitives')
        for kind,stroke,fill,width,points in primitive:
            geometry.color(stroke);geometry.color(fill);geometry.number(width)
            if stroke==fill=='none' or (stroke!='none' and not 1.6<=width<=2):
                raise ValueError('Invisible action or inconsistent stroke: '+key)
            for value in points:geometry.number(value)
            positions=points[:4] if kind=='Line' else points if kind=='Triangle' else points[:2]
            if any(value<0 or value>32 for value in positions):
                raise ValueError('Action geometry is outside its viewbox: '+key)
        records.append((entry,commands,primitive))
        native.append(f'static const Primitive actionGeometry{index}[] = {{')
        for kind,stroke,fill,width,points in primitive:
            coordinates=', '.join(geometry.literal(value) for value in points+[0]*(6-len(points)))
            native.append(f'    {{Shape::{kind}, Tone::{geometry.TONES[stroke]}, Tone::{geometry.TONES[fill]}, {geometry.literal(width)}, {{{coordinates}}}}},')
        native.append('};')
        body='\n'.join('  '+geometry.svg(command) for command in commands)
        filename=key+'.svg'
        generated[ROOT/'svg'/filename]=f'<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" viewBox="0 0 32 32">\n<title>{html.escape(name)}</title>\n<g stroke-linecap="round" stroke-linejoin="round">\n{body}\n</g>\n</svg>\n'
        item={'id':index,'key':key,'name':name,'aliases':entry['aliases'],'primitives':len(primitive),'svg':'svg/'+filename}
        if 'reuse' in entry:item['reuse']=entry['reuse']
        if entry.get('prefixes'):item['prefixes']=entry['prefixes']
        manifest.append(item)
    if REQUIRED-aliases:raise ValueError('Required actions have no icon: '+', '.join(sorted(REQUIRED-aliases)))
    if prefixes!={'recent:'}:raise ValueError('Recent project paths require an explicit icon binding')
    native.append('static const Icon actionCatalog[] = {')
    for index,(entry,_,primitive) in enumerate(records):
        native.append(f'    {{{json.dumps(entry["key"])}, {json.dumps(entry["name"])}, actionGeometry{index}, {len(primitive)}}},')
    native.append('};\nstatic const ActionBinding actionBindings[] = {')
    for index,(entry,_,_) in enumerate(records):
        for alias in entry['aliases']:native.append(f'    {{{json.dumps(alias)}, {index}}},')
    native.append('};\nstatic const ActionPrefix actionPrefixes[] = {')
    for index,(entry,_,_) in enumerate(records):
        for prefix in entry.get('prefixes',[]):native.append(f'    {{{json.dumps(prefix)}, {index}}},')
    native.append('};\n')
    generated[ROOT/'ActionIconData.inc']='\n'.join(native)
    generated[ROOT/'catalog.json']=json.dumps({'viewBox':32,'colors':geometry.COLORS,'icons':manifest},indent=2)+'\n'
    return records,generated

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--preview',type=Path)
    args=parser.parse_args();records,generated=outputs()
    for path,text in generated.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8')!=text:
                raise ValueError('Generated action asset is stale: '+str(path))
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(text,encoding='utf-8',newline='\n')
    if args.preview:
        columns=8;cell_width=150;cell_height=100;rows=(len(records)+columns-1)//columns
        cards=[]
        for index,(entry,commands,_) in enumerate(records):
            x=(index%columns)*cell_width;y=(index//columns)*cell_height
            body=''.join(geometry.svg(command) for command in commands)
            cards.append(f'<g transform="translate({x} {y})"><rect x="4" y="4" width="142" height="92" rx="8" fill="#293647"/><svg x="51" y="10" width="48" height="48" viewBox="0 0 32 32"><g stroke-linecap="round" stroke-linejoin="round">{body}</g></svg><text x="75" y="79" fill="#E4EAF2" text-anchor="middle" font-family="sans-serif" font-size="9">{html.escape(entry["name"])}</text></g>')
        width=columns*cell_width;height=rows*cell_height
        args.preview.parent.mkdir(parents=True,exist_ok=True)
        args.preview.write_text(f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}"><rect width="{width}" height="{height}" fill="#152131"/>'+''.join(cards)+'</svg>\n',encoding='utf-8')
    print(f'{"Verified" if args.check else "Generated"} {len(records)} action icons and explicit action/prefix bindings')

if __name__=='__main__':main()
