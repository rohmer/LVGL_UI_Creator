"""Copy the fourteen user-provided compact tries and regenerate their catalog."""
from pathlib import Path
import argparse
import hashlib
import importlib.util
import json
import struct

PROFILES = [
    ("enUS", "en-US", "en-US", "English (US)"),
    ("esMS", "es-MX", "es-ES", "Spanish"),
    ("frFR", "fr-FR", "fr-FR", "French"),
    ("deDE", "de-DE", "de-DE", "German"),
    ("elEL", "el-EL", "el-GR", "Greek"),
    ("arAR", "ar-AR", "ar-SA", "Arabic"),
    ("hiHI", "hi-HI", "hi-IN", "Hindi"),
]

def identity(data):
    value = 14695981039346656037
    for byte in data:
        value = ((value ^ byte) * 1099511628211) & 0xffffffffffffffff
    return f"trie-{value:016x}"

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("corpus", type=Path, help="folder containing the original NGTR files")
    args = parser.parse_args()
    directory = Path(__file__).resolve().parent
    root = directory.parent.parent
    spec = importlib.util.spec_from_file_location("ngix", root / "LVSerial/Widgets/AdvancedKeyboard/layout/build_ngtr_index.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    records = []
    prepared = []
    for prefix, corpus_locale, language, name in PROFILES:
        for size in (16, 256):
            source = args.corpus / f"{prefix}{size}.ngtr"
            data = source.read_bytes()
            index = module.build_index(data)  # Complete structure validation, not just magic bytes.
            filename = f"{language}-{size}.ngtr"
            records.append({
                "id": f"corpus-{language}-{size}", "language": language,
                "name": f"{name} - {size} KiB", "sourceName": source.name,
                "sourceLocale": corpus_locale, "sizeKiB": size, "bytes": len(data),
                "indexBytes": len(index), "nodeCount": struct.unpack_from("<I", data, 8)[0],
                "filename": filename, "sha256": hashlib.sha256(data).hexdigest(),
                "projectTrieId": identity(data),
            })
            prepared.append((filename, data))
    target = directory / "models"
    target.mkdir(exist_ok=True)
    for filename, data in prepared:
        (target / filename).write_bytes(data)
    catalog = {"version": 1, "source": "User-provided D:/Corpus NGTR files", "models": records}
    (directory / "catalog.json").write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    lines = ["// Generated by import_corpus.py; do not edit separately from catalog.json."]
    for record in records:
        values = [json.dumps(record[key], ensure_ascii=True) for key in ("id", "language", "name", "sourceName")]
        values += [str(record["sizeKiB"]), str(record["bytes"])]
        values += [json.dumps(record[key]) for key in ("filename", "projectTrieId")]
        lines.append("    {" + ", ".join(values) + "},")
    (directory / "CatalogData.inc").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps({"models": len(records), "trieBytes": sum(record["bytes"] for record in records), "output": str(target)}))

if __name__ == "__main__":
    main()
